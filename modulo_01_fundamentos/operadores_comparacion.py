edad = 24
edad_minima = 18

print("=== Operadores de comparación ===")

print(f"Edad: {edad}")
print(f"Edad mínima: {edad_minima}")

print(edad == edad_minima)   # Igual que
print(edad != edad_minima)   # Diferente de
print(edad > edad_minima)    # Mayor que
print(edad < edad_minima)    # Menor que
print(edad >= edad_minima)   # Mayor o igual que
print(edad <= edad_minima)   # Menor o igual que